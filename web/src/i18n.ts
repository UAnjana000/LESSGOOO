export const STRINGS: Record<Lang, Record<Key, string>> = { en, hi, mr };

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s: string = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars ?? {})) {
    s = s.replace(`{${k}}`, typeof v === "number" ? new Intl.NumberFormat(`${lang}-IN`).format(v) : v);
  }
  return s;
}

/** English derivative labels the API sends (spec §1.1, backend KIND_LABELS / PAGE_LABELS / label_shown). */
export const DERIVATIVE_LABELS: Record<string, Key> = {
  "Original scan": "scan",
  "Source text": "labelSourceText",
  "Reviewed transcription": "labelReviewedTranscription",
  "Reviewed transcript": "transcript",
  "Reviewed caption": "labelReviewedCaption",
  "Reviewed translation": "reviewedTranslation",
  "Reviewed summary": "labelReviewedSummary",
  "Synthetic narration": "labelSyntheticNarration",
  "Machine translation — not reviewed": "labelMachineTranslation",
  "AI-generated answer from archive sources": "askLabel",
};

/** Translate an API derivative label; an unknown label is shown as sent, marked as English. */
export function derivativeLabel(lang: Lang, label: string): { text: string; lang: Lang | undefined } {
  const key = DERIVATIVE_LABELS[label];
  return key ? { text: translate(lang, key), lang: undefined } : { text: label, lang: "en" };
}

const DEVANAGARI = /[\u0900-\u097F]/;

/**
 * Best guess at the language of archive text whose language the API does not send (titles, notes),
 * so screen readers switch voice: Devanagari follows the Hindi/Marathi UI (Hindi under the English UI),
 * Latin script is English.
 */
export function textLang(text: string | null | undefined, uiLang: Lang): Lang | undefined {
  if (!text) return undefined;
  if (DEVANAGARI.test(text)) return uiLang === "en" ? "hi" : uiLang;
  return /[A-Za-z]/.test(text) ? "en" : undefined;
}

/** Pick a label from a {en,hi,mr} map, falling back to English with a marker the UI can show. */
export function pick(map: Record<string, string> | undefined, lang: Lang): { text: string; fallback: boolean } {
  if (!map) return { text: "", fallback: false };
  if (map[lang]) return { text: map[lang], fallback: false };
  return { text: map.en ?? Object.values(map)[0] ?? "", fallback: lang !== "en" };
}
